/**
 * @fileoverview Candidate Profile YAML Adapter for the Autonomous Job Application Pipeline.
 *
 * Implements bidirectional transformation between ApplyKit's CandidateProfile aggregate
 * and the canonical profile.yaml format defined in job-application-pipeline/templates/profile.example.yaml (ADR-0044).
 *
 * Invariants:
 * 1. Zero-dependency: pure functional parsing and serialization without external runtime dependencies.
 * 2. Complete evidence grounding: preserves candidate identity, location, preferences, experience claims,
 *    and bullet points verbatim.
 */

import type { CandidateProfile } from './profile.js';
import { createEmptyProfile } from './profile.js';
import type { WorkExperience } from './experience.js';
import type { CandidateProject } from './project.js';
import type { EducationRecord } from './education.js';
import type { CandidateSkill } from './skill.js';
import type { SavedAnswer } from './saved-answer.js';
import type { CandidateClaim } from '../evidence/candidate-claim.js';
import {
  createProfileId,
  createExperienceId,
  createProjectId,
  createEducationId,
  createSkillId,
  createClaimId,
  createSavedAnswerId,
} from '../types/ids.js';

/**
 * Serializes a CandidateProfile aggregate into human-readable profile.yaml format
 * conforming strictly to job-application-pipeline/templates/profile.example.yaml.
 *
 * @param profile Verified candidate profile aggregate.
 * @returns RFC-compliant YAML string.
 */
export function serializePipelineProfileYaml(profile: CandidateProfile): string {
  const lines: string[] = [];

  lines.push('# Candidate profile for the job-application-pipeline skill.');
  lines.push('# Generated by ApplyKit Copilot. Keep this file private.');
  lines.push('');

  // 1. Identity
  const fullName = `${profile.identity.legalFirstName} ${profile.identity.legalLastName}`.trim();
  const stem = `${profile.identity.legalFirstName}_${profile.identity.legalLastName}`.trim().replace(/\s+/g, '_');
  lines.push('identity:');
  lines.push(`  legal_name: "${escapeYamlString(fullName)}"`);
  lines.push(`  preferred_name: "${escapeYamlString(profile.identity.preferredName || '')}"`);
  lines.push(`  filename_stem: "${escapeYamlString(stem || 'Candidate_Resume')}"`);
  lines.push('');

  // 2. Contact for forms
  lines.push('contact_for_forms:');
  lines.push(`  email: "${escapeYamlString(profile.identity.email || '')}"`);
  lines.push(`  phone: "${escapeYamlString(profile.identity.phone || '')}"`);
  lines.push(`  linkedin: "${escapeYamlString(profile.links.linkedin || '')}"`);
  lines.push(`  github: "${escapeYamlString(profile.links.github || '')}"`);
  lines.push(`  website: "${escapeYamlString(profile.links.portfolio || '')}"`);
  const currentCompany = profile.experiences.find((e) => e.isCurrent)?.company || profile.experiences[0]?.company || '';
  lines.push(`  current_employer: "${escapeYamlString(currentCompany)}"`);
  lines.push('');

  // 3. Location
  const authText = profile.identity.workAuthorization.authorizedCountries.length > 0
    ? profile.identity.workAuthorization.authorizedCountries.join(', ')
    : profile.identity.workAuthorization.isAuthorizedInCountry
    ? profile.identity.location.country
    : 'None';
  const languages = profile.skills
    .filter((s) => s.category === 'language')
    .map((s) => s.name);

  lines.push('location:');
  lines.push(`  city: "${escapeYamlString(profile.identity.location.city || '')}"`);
  lines.push(`  country: "${escapeYamlString(profile.identity.location.country || '')}"`);
  lines.push(`  utc_offset: "${escapeYamlString(profile.professional.preferredLocations.find((l) => l.startsWith('UTC') || l.startsWith('+') || l.startsWith('-')) || '')}"`);
  lines.push(`  work_authorisation: "${escapeYamlString(authText)}"`);
  lines.push(`  languages_spoken: [${languages.map((l) => `"${escapeYamlString(l)}"`).join(', ')}]`);
  lines.push('');

  // 4. Preferences
  const noticePeriod = profile.savedAnswers.find((a) => a.canonicalKey === 'notice_period')?.answerText || '';
  const compAsk = profile.savedAnswers.find((a) => a.canonicalKey === 'expected_salary')?.answerText || '';
  lines.push('preferences:');
  lines.push(`  remote_only: ${profile.professional.workplacePreference === 'remote'}`);
  lines.push(`  relocation: ${profile.professional.isOpenToRelocation}`);
  lines.push(`  notice_period: "${escapeYamlString(noticePeriod)}"`);
  lines.push(`  compensation_ask: "${escapeYamlString(compAsk)}"`);
  lines.push('  compensation_floor: ""');
  lines.push('  per_company_cap: 2');
  lines.push('  excluded_companies: []');
  lines.push('');

  // 5. Targeting
  lines.push('targeting:');
  lines.push(`  role_families: [${profile.professional.targetRoles.map((r) => `"${escapeYamlString(r)}"`).join(', ')}]`);
  lines.push(`  seniority: "${escapeYamlString(profile.professional.targetSeniority && profile.professional.targetSeniority !== 'any' ? profile.professional.targetSeniority : profile.professional.headline || '')}"`);
  lines.push(`  must_have_stack: [${profile.skills.slice(0, 5).map((s) => `"${escapeYamlString(s.name)}"`).join(', ')}]`);
  lines.push('');

  // 6. Experience Claims
  lines.push('experience_claims:');
  if (profile.claims.length > 0) {
    for (const claim of profile.claims) {
      lines.push(`  "${escapeYamlString(claim.statement)}": ${claim.confidence}`);
    }
  } else {
    for (const skill of profile.skills.slice(0, 8)) {
      if (skill.yearsOfExperience) {
        lines.push(`  "${escapeYamlString(skill.name)}": ${skill.yearsOfExperience}`);
      }
    }
  }
  lines.push('');

  // 7. Writing Rules
  lines.push('writing_rules:');
  lines.push('  - "No dashes or hyphenated compounds"');
  lines.push('  - "Direct senior engineering voice without robotic AI clichés"');
  lines.push('  closing_sentence: "I welcome the opportunity to discuss how my background aligns with your engineering goals."');
  lines.push('');

  // 8. Experience
  lines.push('experience:');
  if (profile.experiences.length === 0) {
    lines.push('  []');
  } else {
    for (const exp of profile.experiences) {
      lines.push(`  - employer: "${escapeYamlString(exp.company)}"`);
      lines.push(`    title: "${escapeYamlString(exp.title)}"`);
      lines.push(`    dates: "${escapeYamlString(exp.startDate)} - ${escapeYamlString(exp.endDate || (exp.isCurrent ? 'Present' : ''))}"`);
      lines.push(`    location: "${escapeYamlString(exp.location || '')}"`);
      lines.push(`    remote: ${exp.isRemote}`);
      lines.push('    bullets:');
      for (const bullet of exp.highlights) {
        lines.push(`      - "${escapeYamlString(bullet)}"`);
      }
    }
  }
  lines.push('');

  // 9. Projects
  lines.push('projects:');
  if (profile.projects.length === 0) {
    lines.push('  []');
  } else {
    for (const proj of profile.projects) {
      lines.push(`  - name: "${escapeYamlString(proj.title)}"`);
      lines.push(`    description: "${escapeYamlString(proj.description)}"`);
      if (proj.url) {
        lines.push(`    url: "${escapeYamlString(proj.url)}"`);
      }
      lines.push('    bullets:');
      for (const bullet of proj.highlights) {
        lines.push(`      - "${escapeYamlString(bullet)}"`);
      }
    }
  }
  lines.push('');

  // 10. Education
  lines.push('education:');
  if (profile.education.length === 0) {
    lines.push('  []');
  } else {
    for (const edu of profile.education) {
      lines.push(`  - institution: "${escapeYamlString(edu.institution)}"`);
      lines.push(`    degree: "${escapeYamlString(edu.degree)}"`);
      lines.push(`    field: "${escapeYamlString(edu.fieldOfStudy)}"`);
      if (edu.endDate) {
        lines.push(`    graduation_year: "${escapeYamlString(edu.endDate)}"`);
      }
    }
  }
  lines.push('');

  // 11. Skills
  lines.push('skills:');
  const skillsByCategory: Record<string, string[]> = {};
  for (const skill of profile.skills) {
    const cat = skill.category || 'other';
    if (!skillsByCategory[cat]) skillsByCategory[cat] = [];
    skillsByCategory[cat].push(skill.name);
  }
  const categoryLabels: Record<string, string> = {
    language: 'languages',
    framework: 'frameworks',
    database: 'databases',
    cloud_infrastructure: 'cloud_and_infrastructure',
    tool: 'tools',
    methodology: 'methodologies',
    soft_skill: 'soft_skills',
  };
  for (const [cat, names] of Object.entries(skillsByCategory)) {
    const label = categoryLabels[cat] || cat;
    lines.push(`  ${label}: [${names.map((n) => `"${escapeYamlString(n)}"`).join(', ')}]`);
  }
  lines.push('');

  // 12. Resume Variants
  lines.push('resume_variants:');
  for (const role of profile.professional.targetRoles) {
    lines.push(`  - role_family: "${escapeYamlString(role)}"`);
    lines.push(`    summary_emphasis: "Specialized in ${escapeYamlString(role)} architectures."`);
  }
  lines.push('');

  return lines.join('\n');
}

/**
 * Parses a profile.yaml string into a strongly-typed CandidateProfile aggregate.
 *
 * @param yamlString The raw YAML string from candidate's profile.yaml.
 * @param existingProfile Optional base profile to preserve IDs and created timestamps.
 * @returns Parsed and validated CandidateProfile.
 */
export function parsePipelineProfileYaml(
  yamlString: string,
  existingProfile?: CandidateProfile | null
): CandidateProfile {
  const profile = existingProfile
    ? { ...existingProfile }
    : createEmptyProfile(createProfileId());

  const lines = yamlString.split(/\r?\n/);
  let currentSection = '';
  let currentObject: Record<string, any> | null = null;
  let currentSubKey = '';

  const parsedData: Record<string, any> = {
    identity: {},
    contact_for_forms: {},
    location: {},
    preferences: {},
    targeting: {},
    experience_claims: {},
    writing_rules: [],
    experience: [],
    projects: [],
    education: [],
    skills: {},
    resume_variants: [],
  };

  for (let i = 0; i < lines.length; i++) {
    const rawLine = lines[i]!;
    const line = rawLine.trim();

    // Skip empty lines and full-line comments
    if (!line || line.startsWith('#')) {
      continue;
    }

    // Top level section detection (starts with column 0)
    if (/^[a-z_]+:\s*$/i.test(rawLine) || /^[a-z_]+:\s*\[\]/i.test(rawLine)) {
      const match = rawLine.match(/^([a-z_]+):/i);
      if (match && match[1]) {
        currentSection = match[1];
        currentObject = null;
        currentSubKey = '';
        continue;
      }
    }

    if (!currentSection) continue;

    // Handle writing_rules section (mixture of bullet rules and closing_sentence)
    if (currentSection === 'writing_rules') {
      if (line.startsWith('- ')) {
        const ruleText = unescapeYamlValue(line.slice(2).trim());
        if (ruleText) {
          if (!Array.isArray(parsedData.writing_rules)) {
            parsedData.writing_rules = [];
          }
          parsedData.writing_rules.push(ruleText);
        }
        continue;
      }
      if (line.startsWith('closing_sentence:')) {
        const val = unescapeYamlValue(line.slice('closing_sentence:'.length).trim());
        parsedData.closing_sentence = val;
        continue;
      }
    }

    // Handle sections with list of items / objects
    if (
      currentSection === 'experience' ||
      currentSection === 'projects' ||
      currentSection === 'education' ||
      currentSection === 'resume_variants'
    ) {
      const indent = rawLine.search(/\S/);
      const isListItem = line.startsWith('- ');
      const itemContent = isListItem ? line.slice(2).trim() : '';
      const isKvProperty = /^[a-z_]+:\s*(.*)$/i.test(itemContent);

      // Check for nested list bullets under current active property (e.g. bullets:)
      // A bullet starts with "- " and either has indentation >= 4 or is not a top-level item key-value property
      if (
        currentObject &&
        currentSubKey &&
        Array.isArray(currentObject[currentSubKey]) &&
        isListItem &&
        (!isKvProperty || indent >= 4)
      ) {
        currentObject[currentSubKey].push(unescapeYamlValue(itemContent));
        continue;
      }

      if (isListItem) {
        const kvMatch = itemContent.match(/^([a-z_]+):\s*(.*)$/i);
        if (kvMatch && kvMatch[1]) {
          currentObject = {};
          currentObject[kvMatch[1]] = unescapeYamlValue(kvMatch[2] || '');
          parsedData[currentSection].push(currentObject);
          currentSubKey = kvMatch[1];
        } else {
          // Scalar list item
          parsedData[currentSection].push(unescapeYamlValue(itemContent));
        }
        continue;
      }

      // Indented nested properties on the active object
      if (currentObject && line.includes(':')) {
        const subMatch = line.match(/^([a-z_]+):\s*(.*)$/i);
        if (subMatch && subMatch[1]) {
          const key = subMatch[1];
          const val = subMatch[2]?.trim() || '';
          if (val === '') {
            currentSubKey = key;
            currentObject[key] = [];
          } else {
            currentObject[key] = unescapeYamlValue(val);
            currentSubKey = key;
          }
          continue;
        }
      }
      continue;
    }

    // Handle key-value section (identity, contact_for_forms, location, preferences, targeting, experience_claims, skills)
    if (line.includes(':')) {
      let colonIdx = -1;
      if (line.startsWith('"')) {
        const quoteIdx = line.indexOf('":');
        if (quoteIdx !== -1) {
          colonIdx = quoteIdx + 1;
        }
      }
      if (colonIdx === -1) {
        colonIdx = line.indexOf(':');
      }

      const key = unescapeYamlValue(line.slice(0, colonIdx).trim());
      const val = line.slice(colonIdx + 1).trim();

      if (!parsedData[currentSection]) {
        parsedData[currentSection] = {};
      }

      if (val.startsWith('[') && val.endsWith(']')) {
        const items = val
          .slice(1, -1)
          .split(',')
          .map((s) => unescapeYamlValue(s.trim()))
          .filter(Boolean);
        parsedData[currentSection][key] = items;
      } else {
        parsedData[currentSection][key] = unescapeYamlValue(val);
      }
    }
  }

  // Populate CandidateProfile Aggregate
  const idData = parsedData.identity || {};
  const contactData = parsedData.contact_for_forms || {};
  const locData = parsedData.location || {};
  const prefData = parsedData.preferences || {};
  const targetData = parsedData.targeting || {};

  // Parse legal name into first/last
  let firstName = profile.identity.legalFirstName;
  let lastName = profile.identity.legalLastName;
  if (idData.legal_name) {
    const parts = idData.legal_name.trim().split(/\s+/);
    firstName = parts[0] || '';
    lastName = parts.slice(1).join(' ') || '';
  }

  const importedAuthorization = typeof locData.work_authorisation === 'string'
    ? locData.work_authorisation
      .split(',')
      .map((country: string) => country.trim())
      .filter((country: string) => country.length > 0 && country.toLowerCase() !== 'none')
    : null;

  const updatedIdentity = {
    ...profile.identity,
    legalFirstName: firstName,
    legalLastName: lastName,
    preferredName: idData.preferred_name || profile.identity.preferredName,
    email: contactData.email || profile.identity.email,
    phone: contactData.phone || profile.identity.phone,
    location: {
      city: locData.city || profile.identity.location.city,
      country: locData.country || profile.identity.location.country,
    },
    workAuthorization: {
      ...profile.identity.workAuthorization,
      authorizedCountries: importedAuthorization ?? profile.identity.workAuthorization.authorizedCountries,
      isAuthorizedInCountry: importedAuthorization
        ? importedAuthorization.length > 0
        : profile.identity.workAuthorization.isAuthorizedInCountry,
    },
  };

  const updatedLinks = {
    ...profile.links,
    linkedin: contactData.linkedin || profile.links.linkedin,
    github: contactData.github || profile.links.github,
    portfolio: contactData.website || profile.links.portfolio,
  };

  const updatedProfessional = {
    ...profile.professional,
    headline: targetData.seniority || profile.professional.headline,
    targetSeniority: ['intern', 'junior', 'mid', 'senior', 'staff', 'principal', 'any'].includes(
      String(targetData.seniority).toLowerCase()
    )
      ? String(targetData.seniority).toLowerCase() as NonNullable<typeof profile.professional.targetSeniority>
      : profile.professional.targetSeniority,
    targetRoles: Array.isArray(targetData.role_families) && targetData.role_families.length > 0
      ? targetData.role_families
      : profile.professional.targetRoles,
    workplacePreference: prefData.remote_only ? ('remote' as const) : profile.professional.workplacePreference,
    isOpenToRelocation: typeof prefData.relocation === 'boolean' ? prefData.relocation : profile.professional.isOpenToRelocation,
  };

  // Convert experiences
  const parsedExperiences: WorkExperience[] = [];
  if (Array.isArray(parsedData.experience)) {
    for (const exp of parsedData.experience) {
      if (typeof exp === 'object' && exp !== null && (exp.employer || exp.title)) {
        const dates = (exp.dates || '').split(/\s+-\s+/).map((d: string) => d.trim());
        parsedExperiences.push({
          id: createExperienceId(),
          company: exp.employer || 'Company',
          title: exp.title || 'Engineer',
          employmentType: 'full_time',
          location: exp.location || locData.city || 'Remote',
          isRemote: exp.remote ?? true,
          startDate: dates[0] || '2020-01',
          endDate: dates[1] && dates[1].toLowerCase() !== 'present' ? dates[1] : undefined,
          isCurrent: !dates[1] || dates[1].toLowerCase() === 'present',
          description: exp.description || '',
          highlights: Array.isArray(exp.bullets) ? exp.bullets : [],
          technologiesUsed: [],
          evidenceRefs: [],
        });
      }
    }
  }

  // Convert projects
  const parsedProjects: CandidateProject[] = [];
  if (Array.isArray(parsedData.projects)) {
    for (const proj of parsedData.projects) {
      if (typeof proj === 'object' && proj !== null && proj.name) {
        parsedProjects.push({
          id: createProjectId(),
          title: proj.name,
          description: proj.description || '',
          url: proj.url,
          highlights: Array.isArray(proj.bullets) ? proj.bullets : [],
          technologiesUsed: [],
          evidenceRefs: [],
        });
      }
    }
  }

  // Convert education
  const parsedEducation: EducationRecord[] = [];
  if (Array.isArray(parsedData.education)) {
    for (const edu of parsedData.education) {
      if (typeof edu === 'object' && edu !== null && edu.institution) {
        parsedEducation.push({
          id: createEducationId(),
          institution: edu.institution,
          degree: edu.degree || 'Degree',
          fieldOfStudy: edu.field || 'Computer Science',
          endDate: edu.graduation_year,
          isCompleted: true,
          honors: [],
          relevantCoursework: [],
          activities: [],
          evidenceRefs: [],
        });
      }
    }
  }

  // Convert skills
  const parsedSkills: CandidateSkill[] = [];
  if (typeof parsedData.skills === 'object' && parsedData.skills !== null) {
    for (const [catName, skillList] of Object.entries(parsedData.skills)) {
      if (Array.isArray(skillList)) {
        for (const sName of skillList) {
          const strName = String(sName).trim();
          if (strName) {
            parsedSkills.push({
              id: createSkillId(),
              name: strName,
              normalizedName: strName.toLowerCase().replace(/[^a-z0-9]/g, ''),
              category: mapSkillCategory(catName),
              proficiency: 'expert',
              evidenceRefs: [],
            });
          }
        }
      }
    }
  }

  // If no skills were grouped, add languages_spoken as skills
  if (Array.isArray(locData.languages_spoken)) {
    for (const lang of locData.languages_spoken) {
      const strLang = String(lang).trim();
      if (strLang && !parsedSkills.some((s) => s.normalizedName === strLang.toLowerCase())) {
        parsedSkills.push({
          id: createSkillId(),
          name: strLang,
          normalizedName: strLang.toLowerCase(),
          category: 'language',
          proficiency: 'expert',
          evidenceRefs: [],
        });
      }
    }
  }

  // Convert experience claims
  const parsedClaims: CandidateClaim[] = [];
  if (typeof parsedData.experience_claims === 'object' && parsedData.experience_claims !== null) {
    for (const [stmt, conf] of Object.entries(parsedData.experience_claims)) {
      parsedClaims.push({
        id: createClaimId(),
        statement: stmt,
        claimType: 'years_experience',
        supportedByEvidenceIds: [],
        confidence: typeof conf === 'number' ? Math.min(1.0, Math.max(0, conf)) : 1.0,
        tags: ['pipeline_claim'],
        createdAt: new Date().toISOString(),
      });
    }
  }

  // Construct updated saved answers for notice period and salary ask
  const updatedSavedAnswers = [...profile.savedAnswers];
  if (prefData.notice_period) {
    const existingIdx = updatedSavedAnswers.findIndex((a) => a.canonicalKey === 'notice_period');
    const answerObj: SavedAnswer = {
      id: existingIdx >= 0 ? updatedSavedAnswers[existingIdx]!.id : createSavedAnswerId(),
      canonicalKey: 'notice_period',
      promptPatterns: ['notice period', 'earliest start date'],
      answerText: prefData.notice_period,
      category: 'notice_period',
      tags: ['availability'],
      evidenceRefs: [],
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    };
    if (existingIdx >= 0) {
      updatedSavedAnswers[existingIdx] = answerObj;
    } else {
      updatedSavedAnswers.push(answerObj);
    }
  }
  if (prefData.compensation_ask) {
    const existingIdx = updatedSavedAnswers.findIndex((a) => a.canonicalKey === 'expected_salary');
    const answerObj: SavedAnswer = {
      id: existingIdx >= 0 ? updatedSavedAnswers[existingIdx]!.id : createSavedAnswerId(),
      canonicalKey: 'expected_salary',
      promptPatterns: ['compensation', 'salary expectation', 'desired salary'],
      answerText: prefData.compensation_ask,
      category: 'salary_expectations',
      tags: ['compensation'],
      evidenceRefs: [],
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    };
    if (existingIdx >= 0) {
      updatedSavedAnswers[existingIdx] = answerObj;
    } else {
      updatedSavedAnswers.push(answerObj);
    }
  }

  return {
    ...profile,
    updatedAt: new Date().toISOString(),
    identity: updatedIdentity,
    links: updatedLinks,
    professional: updatedProfessional,
    experiences: parsedExperiences.length > 0 ? parsedExperiences : profile.experiences,
    projects: parsedProjects.length > 0 ? parsedProjects : profile.projects,
    education: parsedEducation.length > 0 ? parsedEducation : profile.education,
    skills: parsedSkills.length > 0 ? parsedSkills : profile.skills,
    claims: parsedClaims.length > 0 ? parsedClaims : profile.claims,
    savedAnswers: updatedSavedAnswers,
  };
}

/**
 * Escapes special YAML characters in scalar strings.
 */
function escapeYamlString(val: string): string {
  return val.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

/**
 * Unescapes quoted or unquoted YAML scalar strings.
 */
function unescapeYamlValue(val: string): any {
  const trimmed = val.trim();
  if (trimmed === 'true') return true;
  if (trimmed === 'false') return false;
  if (/^-?\d+(\.\d+)?$/.test(trimmed)) return Number(trimmed);
  if (trimmed.startsWith('"') && trimmed.endsWith('"')) {
    return trimmed.slice(1, -1).replace(/\\"/g, '"').replace(/\\\\/g, '\\');
  }
  if (trimmed.startsWith("'") && trimmed.endsWith("'")) {
    return trimmed.slice(1, -1);
  }
  return trimmed;
}

/**
 * Maps raw category names from YAML into CandidateSkill category taxonomy.
 */
function mapSkillCategory(catName: string): CandidateSkill['category'] {
  const normalized = catName.toLowerCase();
  if (normalized.includes('language')) return 'language';
  if (normalized.includes('framework')) return 'framework';
  if (normalized.includes('database')) return 'database';
  if (normalized.includes('cloud') || normalized.includes('infra')) return 'cloud_infrastructure';
  if (normalized.includes('devops')) return 'devops_tool';
  if (normalized.includes('architecture')) return 'architecture_pattern';
  if (normalized.includes('testing')) return 'testing_qa';
  return 'domain_expertise';
}
